#!/usr/bin/env python3
"""Render the vector logo to a compact, 16-level coverage mask for core X11."""
from pathlib import Path
import io, subprocess
from PIL import Image

HERE = Path(__file__).resolve().parent

def main():
    png = subprocess.check_output(['rsvg-convert', '-w', '336', '-h', '168',
                                   str(HERE / 'helios-logo.svg')])
    alpha = Image.open(io.BytesIO(png)).getchannel('A').resize(
        (84, 42), Image.Resampling.LANCZOS)
    levels = [(v * 15 + 127) // 255 for v in alpha.tobytes()]
    text = '/* Generated by render_logo.py from helios-logo.svg. */\n'
    text += '#define logo_width 84\n#define logo_height 42\n'
    text += 'static const unsigned char logo_alpha[] = {\n'
    text += ''.join('    ' + ','.join(map(str, levels[i:i+84])) + ',\n'
                    for i in range(0, len(levels), 84))
    text += '};\n'
    target = HERE / 'helios-logo-mask.h'
    if not target.exists() or target.read_text() != text:
        target.write_text(text)

if __name__ == '__main__':
    main()
