#!/usr/bin/env python3
"""Render the text of the Perihelion logo (as drawn by the vintage perilogo
client) to XBM bitmaps for the XDM login screen, so that the X display needs
none of the X11R2 fonts.

Usage: render_perilogo.py FONTDIR > perilogo-text.h
FONTDIR holds the Helios X11R2 SNF fonts vr-40.snf and vgl-40.snf
(lib/x11/fonts/r2 in the vintage supplemental tree).
"""
import struct, sys
from pathlib import Path


def charinfo(b, o):
    lsb, rsb, width, asc, desc, attr, bits = struct.unpack_from('<hhhhhHI', b, o)
    return dict(lsb=lsb, rsb=rsb, width=width, ascent=asc, descent=desc,
                offset=bits & 0xffffff, exists=(bits >> 24) & 1)


def read_snf(path):
    """Little-endian SNF version 4: LSB-first bits, rows padded to 32 bits."""
    b = Path(path).read_bytes()
    first, last = struct.unpack_from('<2I', b, 28)
    nchars = last - first + 1
    glyphs = {}
    base = 108 + 16 * nchars
    for i in range(nchars):
        ci = charinfo(b, 108 + 16 * i)
        w, h = ci['rsb'] - ci['lsb'], ci['ascent'] + ci['descent']
        rows = []
        if ci['exists'] and w > 0 and h > 0:
            stride = (w + 31) // 32 * 4
            for r in range(h):
                row = b[base + ci['offset'] + r * stride:][:stride]
                rows.append([(row[x >> 3] >> (x & 7)) & 1 for x in range(w)])
        glyphs[first + i] = (ci, rows)
    return glyphs


def render(glyphs, text):
    """Return (width, height, ascent, pixel rows, per-character boxes)."""
    asc = max(glyphs[ord(c)][0]['ascent'] for c in text)
    desc = max(glyphs[ord(c)][0]['descent'] for c in text)
    width = sum(glyphs[ord(c)][0]['width'] for c in text)
    rows = [[0] * width for _ in range(asc + desc)]
    boxes, x = [], 0
    for c in text:
        ci, bits = glyphs[ord(c)]
        top = asc - ci['ascent']
        for y, line in enumerate(bits):
            for dx, v in enumerate(line):
                if v and 0 <= x + ci['lsb'] + dx < width:
                    rows[top + y][x + ci['lsb'] + dx] = 1
        boxes.append((x + ci['lsb'], top, ci['rsb'] - ci['lsb'], ci['ascent'] + ci['descent']))
        x += ci['width']
    return width, asc + desc, asc, rows, boxes


def xbm(name, width, rows):
    data = []
    for line in rows:
        line = line + [0] * (-len(line) % 8)
        data += [sum(line[i + k] << k for k in range(8)) for i in range(0, len(line), 8)]
    text = '#define %s_width %d\n#define %s_height %d\n' % (name, width, name, len(rows))
    text += 'static char %s_bits[] = {\n' % name
    text += ''.join('    ' + ','.join('0x%02x' % v for v in data[i:i + 12]) + ',\n'
                    for i in range(0, len(data), 12))
    return text + '};\n'


def main(fontdir):
    fontdir = Path(fontdir)
    x_width, x_height, _, x_rows, _ = render(read_snf(fontdir / 'vgl-40.snf'), 'X Window System')
    word = 'PERIHELION'
    p_width, p_height, p_ascent, p_rows, boxes = render(read_snf(fontdir / 'vr-40.snf'), word)
    # perilogo draws the O as a filled disc: drop its glyph, keep its ink box.
    bx, by, bw, bh = boxes[word.rindex('O')]
    ink = [(x, y) for y in range(by, by + bh) for x in range(bx, bx + bw) if p_rows[y][x]]
    ox, oy = min(x for x, _ in ink), min(y for _, y in ink)
    ow = max(x for x, _ in ink) - ox + 1
    oh = max(y for _, y in ink) - oy + 1
    for x, y in ink:
        p_rows[y][x] = 0
    out = '/* Generated by render_perilogo.py from the Helios X11R2 fonts vgl-40\n'
    out += ' * and vr-40 (public domain), as used by the vintage perilogo client. */\n'
    out += xbm('perilogo_x', x_width, x_rows)
    out += xbm('perilogo_word', p_width, p_rows)
    out += '#define perilogo_word_ascent %d\n' % p_ascent
    out += '#define perilogo_disc_x %d\n#define perilogo_disc_y %d\n' % (ox, oy)
    out += '#define perilogo_disc_width %d\n#define perilogo_disc_height %d\n' % (ow, oh)
    sys.stdout.write(out)


if __name__ == '__main__':
    main(sys.argv[1])
